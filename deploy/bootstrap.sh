#!/usr/bin/env bash
# One-command demo server for YARI Academy on a fresh Ubuntu 22.04/24.04 machine.
#
#   git clone <repo> yari && cd yari && sudo ./deploy/bootstrap.sh [domain]
#
# With no domain it uses <server-ip>.sslip.io, which resolves to this server and gets a real
# HTTPS certificate, so a presentation needs no DNS change. Re-running it updates the app.
set -euo pipefail
cd "$(dirname "$0")/.."

log() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
[ "$(id -u)" -eq 0 ] || { echo "Run with sudo."; exit 1; }

if ! command -v docker >/dev/null; then
  log "Installing Docker"
  curl -fsSL https://get.docker.com | sh
fi

# ClamAV needs ~1.5 GB of memory while loading its signatures; add swap on small servers.
mem_kb=$(awk '/MemTotal/ {print $2}' /proc/meminfo)
if [ "$mem_kb" -lt 3800000 ] && ! swapon --show | grep -q /swapfile; then
  log "Adding 2 GB of swap (this server has $((mem_kb / 1024)) MB of memory)"
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

if command -v ufw >/dev/null; then
  ufw allow OpenSSH >/dev/null; ufw allow 80/tcp >/dev/null; ufw allow 443 >/dev/null; ufw --force enable >/dev/null
fi

ENV_FILE=.env.production
if [ ! -f "$ENV_FILE" ]; then
  log "Creating $ENV_FILE with fresh secrets"
  ip=$(curl -fsS https://checkip.amazonaws.com || curl -fsS https://ifconfig.me)
  domain="${1:-${ip//./-}.sslip.io}"
  key_id="k$(date +%Y%m%d)"
  umask 077
  cat > "$ENV_FILE" <<ENV
# Generated by deploy/bootstrap.sh on $(date -u +%F). Keep this file private and backed up
# separately: without these keys the encrypted personal data can't be read.
DOMAIN=$domain
APP_URL=https://$domain
DEMO_MODE=true
POSTGRES_PASSWORD=$(openssl rand -hex 24)
FIELD_ENC_KEYS='{"$key_id":"$(openssl rand -base64 32)"}'
FIELD_ENC_ACTIVE_KEY=$key_id
BLIND_INDEX_KEY=$(openssl rand -base64 32)
DEMO_PASSWORD=$(openssl rand -base64 12 | tr -d '/+=' | cut -c1-12)-Demo
EMAIL_FROM="YARI Academy <academy@yarigroup.co.za>"
RESEND_API_KEY=
STORAGE_DRIVER=local
ENV
fi
set -a; . ./"$ENV_FILE"; set +a

compose() { docker compose -f docker-compose.prod.yml --env-file "$ENV_FILE" "$@"; }

log "Building and starting (first run takes 5-10 minutes)"
compose up -d --build

log "Waiting for the app to be ready"
for _ in $(seq 1 90); do
  [ "$(docker inspect -f '{{.State.Health.Status}}' "$(compose ps -q app)" 2>/dev/null)" = healthy ] && break
  sleep 5
done

if [ "${DEMO_MODE:-false}" = "true" ]; then
  log "Loading demo data"
  compose exec -T -e DEMO_PASSWORD="$DEMO_PASSWORD" app npm run --silent db:seed:demo | tee deploy/demo-logins.txt
  chmod 600 deploy/demo-logins.txt
fi

# Nightly job: at-risk alerts, missing certificates, retention clean-up (02:00 SAST = 00:00 UTC).
cron_line="0 0 * * * cd $(pwd) && docker compose -f docker-compose.prod.yml --env-file $ENV_FILE exec -T app npm run --silent jobs:nightly >> /var/log/yari-nightly.log 2>&1"
( crontab -l 2>/dev/null | grep -v 'jobs:nightly'; echo "$cron_line" ) | crontab -

log "Done: $APP_URL"
echo "Demo logins are in deploy/demo-logins.txt (readable by root only)."
