#!/usr/bin/env bash
# One-command YARI Academy server on a fresh Ubuntu 22.04/24.04 machine (x86 or ARM).
#
#   git clone <repo> yari && cd yari
#   sudo ./deploy/bootstrap.sh [domain]                  # demo server: fictional data, no emails
#   sudo ./deploy/bootstrap.sh --live academy.example    # live platform: real email, first admin
#
# With no domain it uses <server-ip>.sslip.io, which resolves to this server and gets a real
# HTTPS certificate, so it works before any DNS change. Re-running it updates the app.
set -euo pipefail
cd "$(dirname "$0")/.."

log() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
die() { printf '\n%s\n' "$*" >&2; exit 1; }
[ "$(id -u)" -eq 0 ] || die "Run with sudo."

mode=demo
if [ "${1:-}" = "--live" ]; then mode=live; shift; fi

if ! command -v docker >/dev/null; then
  log "Installing Docker"
  curl -fsSL https://get.docker.com | sh
fi

# ClamAV needs ~1.5 GB of memory while loading its signatures; add swap on small servers.
mem_kb=$(awk '/MemTotal/ {print $2}' /proc/meminfo)
if [ "$mem_kb" -lt 3800000 ] && ! swapon --show | grep -q /swapfile; then
  log "Adding 2 GB of swap (this server has $((mem_kb / 1024)) MB of memory)"
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

if [ -f /etc/iptables/rules.v4 ]; then
  # Oracle Cloud's Ubuntu images block everything but SSH with saved iptables rules (and
  # ufw must not be used there). Open the web ports and save the rules.
  for port in 80 443; do
    iptables -C INPUT -p tcp --dport "$port" -j ACCEPT 2>/dev/null ||
      iptables -I INPUT 1 -p tcp --dport "$port" -j ACCEPT
  done
  iptables -C INPUT -p udp --dport 443 -j ACCEPT 2>/dev/null || iptables -I INPUT 1 -p udp --dport 443 -j ACCEPT
  netfilter-persistent save >/dev/null 2>&1 || iptables-save > /etc/iptables/rules.v4
elif command -v ufw >/dev/null; then
  ufw allow OpenSSH >/dev/null; ufw allow 80/tcp >/dev/null; ufw allow 443 >/dev/null; ufw --force enable >/dev/null
fi

ENV_FILE=.env.production
if [ ! -f "$ENV_FILE" ]; then
  log "Creating $ENV_FILE with fresh secrets"
  ip=$(curl -fsS https://checkip.amazonaws.com || curl -fsS https://ifconfig.me)
  domain="${1:-${ip//./-}.sslip.io}"
  key_id="k$(date +%Y%m%d)"
  if [ "$mode" = live ]; then
    echo "Live set-up. The values you type are saved only in $ENV_FILE on this server."
    read -rp "  First Super Admin's email: " admin_email
    read -rp "  First Super Admin's full name: " admin_name
    read -rsp "  Resend API key (starts with re_; hidden as you type): " resend_key; echo
    [ -n "$admin_email" ] && [ -n "$admin_name" ] || die "The admin's email and name are required."
    case "$resend_key" in re_*) ;; *) die "That doesn't look like a Resend API key (re_...)." ;; esac
    extra="DEMO_MODE=false
RESEND_API_KEY=$resend_key
SEED_ADMIN_EMAIL=$admin_email
SEED_ADMIN_NAME=\"$admin_name\""
  else
    extra="DEMO_MODE=true
RESEND_API_KEY=
DEMO_PASSWORD=$(openssl rand -base64 12 | tr -d '/+=' | cut -c1-12)-Demo"
  fi
  umask 077
  cat > "$ENV_FILE" <<ENV
# Generated by deploy/bootstrap.sh on $(date -u +%F). Keep a copy somewhere safe and separate
# from the backups (e.g. a password manager): without these keys the encrypted personal data
# can't be read, and the backups can't be opened.
DOMAIN=$domain
APP_URL=https://$domain
$extra
POSTGRES_PASSWORD=$(openssl rand -hex 24)
FIELD_ENC_KEYS='{"$key_id":"$(openssl rand -base64 32)"}'
FIELD_ENC_ACTIVE_KEY=$key_id
BLIND_INDEX_KEY=$(openssl rand -base64 32)
BACKUP_PASSPHRASE=$(openssl rand -base64 32)
EMAIL_FROM="YARI Academy <academy@yarigroup.co.za>"
STORAGE_DRIVER=local
ENV
fi
set -a; . ./"$ENV_FILE"; set +a

# Never turn a demo server into the live one: its database is full of fictional people.
if [ "$mode" = live ] && [ "${DEMO_MODE:-false}" = "true" ]; then
  die "This server was set up as a demo. To make it live, wipe it first:
  sudo docker compose -f docker-compose.prod.yml --env-file $ENV_FILE down -v && sudo rm $ENV_FILE
then run: sudo ./deploy/bootstrap.sh --live <domain>"
fi

compose() { docker compose -f docker-compose.prod.yml --env-file "$ENV_FILE" "$@"; }

log "Building and starting (first run takes 5-10 minutes)"
compose up -d --build

log "Waiting for the app to be ready"
for _ in $(seq 1 90); do
  [ "$(docker inspect -f '{{.State.Health.Status}}' "$(compose ps -q app)" 2>/dev/null)" = healthy ] && break
  sleep 5
done

if [ "${DEMO_MODE:-false}" = "true" ]; then
  log "Loading demo data"
  compose exec -T -e DEMO_PASSWORD="$DEMO_PASSWORD" app npm run --silent db:seed:demo | tee deploy/demo-logins.txt
  chmod 600 deploy/demo-logins.txt
else
  # Creates the course templates and, the first time only, the Super Admin's invitation.
  log "Preparing the platform"
  compose exec -T app npm run --silent db:seed
fi

# Nightly job: at-risk alerts, missing certificates, retention clean-up (02:00 SAST = 00:00 UTC),
# then an encrypted backup of the database and uploaded files (02:30 SAST).
chmod 700 deploy/backup.sh
nightly="0 0 * * * cd $(pwd) && docker compose -f docker-compose.prod.yml --env-file $ENV_FILE exec -T app npm run --silent jobs:nightly >> /var/log/yari-nightly.log 2>&1"
backup="30 0 * * * $(pwd)/deploy/backup.sh >> /var/log/yari-backup.log 2>&1"
( crontab -l 2>/dev/null | grep -v -e 'jobs:nightly' -e 'deploy/backup.sh'; echo "$nightly"; echo "$backup" ) | crontab -

log "Done: $APP_URL"
if [ "${DEMO_MODE:-false}" = "true" ]; then
  echo "Demo logins are in deploy/demo-logins.txt (readable by root only)."
else
  echo "Open the Super Admin invitation link above to set the password and two-step verification."
  echo "Nightly encrypted backups go to /var/backups/yari. Copy them off this server regularly."
fi
